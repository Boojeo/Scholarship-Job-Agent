VAULT_KINDS = {
    "transcript": "Transcript", "moi": "MOI_Certificate", "passport": "Passport", "iqama": "Residence_Permit",
    "residence": "Residence_Permit", "recommendation": "Recommendation", "reference": "Recommendation",
    "degree": "Enrollment_or_Degree_Certificate", "enrollment": "Enrollment_or_Degree_Certificate",
    "ielts": "IELTS", "writing_sample": "Writing_Sample_Paper", "certificates": "Certificates",
    "class_rank": "Class_Rank_or_Honors_Letter", "secondary": "Secondary_School_Certificate", "honors": "Class_Rank_or_Honors_Letter",
}
PAPER_URL = "https://arxiv.org/pdf/2610.04047"
PAPER_FILE = "writing_sample_periscope_arxiv.pdf"


def ensure_paper(settings: Settings) -> Path | None:
    """Download the Periscope paper once into the vault as a writing sample. Returns its path or None."""
    import httpx

    target = settings.vault_dir / "attachments" / PAPER_FILE
    if target.exists():
        return target
    try:
        r = httpx.get(PAPER_URL, follow_redirects=True, timeout=60)
        r.raise_for_status()
        if not r.content.startswith(b"%PDF"):
            return None
    except httpx.HTTPError:
        return None
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(r.content)
    return target
CAT_SHORT = {"CATEGORY_1_SCHOLARSHIP": "Scholarship", "CATEGORY_2_COOP_PARTTIME": "Coop",
             "CATEGORY_3_FULLTIME": "Job"}


def _slug(text: str, n: int = 40) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "-", text or "").strip("-")[:n] or "item"


def vault_files(settings: Settings) -> dict[str, list[Path]]:
    found: dict[str, list[Path]] = {}
    folder = settings.vault_dir / "attachments"
    for f in sorted(folder.glob("*")) if folder.exists() else []:
        if f.is_file() and not f.name.startswith("."):
            for key, label in VAULT_KINDS.items():
                if key in f.name.lower():
                    found.setdefault(label, []).append(f)
                    break
    return found


def missing_documents(settings: Settings, required: list[str]) -> list[str]:
    have = {k.lower() for k in vault_files(settings)}
    missing = []
    for doc in required:
        d = doc.lower()
        if any(word in d for word in ("cv", "resume", "statement", "letter of motivation", "cover letter", "sop")):
            continue  # generated by the agent
        if not any(h.split("_")[0] in d or d.split()[0] in h for h in have):
            missing.append(doc)
    return missing


def build_kit(settings: Settings, opp: dict, result: TailorResult) -> Path:
    pkg = result.package
    if opp["category"] == "CATEGORY_1_SCHOLARSHIP":
        ensure_paper(settings)
    folder = settings.kits_dir / (f"{dt.date.today()}_{CAT_SHORT.get(opp['category'], 'Item')}_"
                                  f"{_slug(opp.get('organization') or 'Org', 30)}_{_slug(opp['title'], 40)}")
    folder.mkdir(parents=True, exist_ok=True)
    render_both(fill_contacts(pkg.cv_markdown, settings), folder / "01_Tailored_CV")
    letter_name = "02_Statement_of_Purpose" if opp["category"] == "CATEGORY_1_SCHOLARSHIP" else "02_Cover_Letter"
    render_both(fill_contacts(pkg.letter_markdown, settings), folder / letter_name)
    (folder / "03_Email.txt").write_text(f"Subject: {pkg.email_subject}\n\n{fill_contacts(pkg.email_body, settings)}\n",
                                         encoding="utf-8")
    copied = []
    for label, files in vault_files(settings).items():
        for i, f in enumerate(files, 1):
            name = f"{label}{'_' + str(i) if len(files) > 1 else ''}{f.suffix}"
            shutil.copy2(f, folder / name)
            copied.append(name)
    missing = missing_documents(settings, pkg.required_documents)
    answers = "\n\n".join(f"**{a.question}**\n\n{fill_contacts(a.answer, settings)}" for a in pkg.portal_answers)
    warn = ("\n> ⚠️ Fabrication check flagged these claims - fix or remove them before sending:\n" +
            "\n".join(f"> - {c}" for c in result.unsupported) + "\n") if result.unsupported else ""
    (folder / "00_APPLICATION_INSTRUCTIONS.md").write_text(f"""# {opp['title']}
**Organization:** {opp.get('organization') or '-'}  
**Location:** {opp.get('location') or '-'}  
**Deadline:** {opp.get('deadline') or 'unknown - check the page'}  
**Apply here:** {opp['direct_url']}  
**Match score:** {opp.get('match_score') or '-'} - {opp.get('why_it_matches') or ''}
{warn}
## Files in this folder
- `01_Tailored_CV.pdf` / `.docx`
- `{letter_name}.pdf` / `.docx`
- `03_Email.txt` (send it yourself; nothing is emailed automatically)
{chr(10).join(f'- `{c}`' for c in copied) or '- (no vault attachments found: add transcript, MOI letter, passport to vault/attachments)'}

## Documents the posting asks for that are NOT in your vault
{chr(10).join(f'- {m}' for m in missing) or '- none detected'}

## Steps
1. Open the link above and read the eligibility section once more.
2. Create the account yourself if the portal needs one (the agent never creates accounts or pays fees).
3. Upload the CV and letter from this folder; copy answers from below.
4. Re-read everything on the final review page, then submit.

## Copy-paste answers
{answers or '-'}
""", encoding="utf-8")
    (folder / "opportunity.json").write_text(json.dumps(opp, ensure_ascii=False, indent=2, default=str),
                                              encoding="utf-8")
    return folder


def open_folder(path: Path) -> None:
    if sys.platform.startswith("win"):
        os.startfile(path)  # type: ignore[attr-defined]  # noqa: S606
    elif sys.platform == "darwin":
        subprocess.Popen(["open", str(path)])  # noqa: S603, S607
    else:
        subprocess.Popen(["xdg-open", str(path)])  # noqa: S603, S607
